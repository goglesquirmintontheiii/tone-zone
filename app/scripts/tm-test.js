// Tone Match end-to-end test: renders a known rig as the "song", imports it, runs a quick match and screenshots.
// usage: node scripts/tm-test.js outdir [depth]
const { _electron: electron } = require('playwright');
const path = require('path');
const fs = require('fs');
(async () => {
  const out = process.argv[2] || '/tmp/tm';
  const depth = process.argv[3] || 'quick';
  fs.mkdirSync(out, { recursive: true });
  const app = await electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, '..'), '--no-sandbox'], env: { ...process.env, TZ_DEBUG: '1' } });
  const win = await app.firstWindow();
  const logs = [];
  win.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
  win.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.stack));
  await win.setViewportSize({ width: 1600, height: 950 }).catch(() => {});
  await win.waitForTimeout(4000);
  const info = await win.evaluate(async (depth) => {
    const S = await import('./js/tonematch/search.js');
    const C = await import('./js/catalog/index.js');
    const amps = C.allDefs().filter((d) => d.algo === 'amp' && d.cat === 'Amp');
    const cabs = C.allDefs().filter((d) => d.algo === 'cab' && d.cat === 'Cab');
    const amp = amps.find((d) => /plexi|jcm|800/i.test(d.name + d.ref)) || amps[0];
    const cab = cabs.find((d) => /4x12/i.test(d.id + d.name)) || cabs[0];
    const rig = [{ type: amp.id, params: { 'pos:gain': 0.7 } }, { type: cab.id, params: {} }];
    const p = await window.tz.tm.preview(window.__tz.buildGraph(S.rigPreset(rig)), null);
    return { p, amp: amp.name, cab: cab.name, nAmps: amps.length, nCabs: cabs.length };
  }, depth);
  console.log('target rig', JSON.stringify(info));
  await win.evaluate(() => document.querySelector('[data-tab="tonematch"]').click());
  await win.waitForTimeout(800);
  await win.screenshot({ path: out + '/tm-home.png' });
  await win.evaluate(async ({ p, depth }) => {
    const m = await window.tz.tm.importPath(p);
    m.title = 'Test target';
    m.opts = { depth };
    await window.tz.tm.save(m);
    const mod = await import('./js/pages/tonematch.js');
    await mod.afterImport(m);
  }, { p: info.p, depth });
  await win.waitForTimeout(2500);
  await win.screenshot({ path: out + '/tm-project0.png' });
  const t0 = Date.now();
  await win.evaluate(() => document.querySelector('.tm-big').click());
  await win.waitForTimeout(8000);
  await win.screenshot({ path: out + '/tm-matching.png' });
  await win.waitForFunction(() => !document.querySelector('[data-bar="match"]'), null, { timeout: 900000 });
  console.log('match secs', (Date.now() - t0) / 1000);
  await win.waitForTimeout(800);
  const res = await win.evaluate(() => [...document.querySelectorAll('.tm-res')].map((r) => r.innerText.replace(/\s+/g, ' ')));
  console.log(res.join('\n'));
  console.log(await win.evaluate(async () => JSON.stringify((await window.tz.tm.list())[0].result.dbg)));
  await win.evaluate(() => document.querySelector('.tm-res').scrollIntoView());
  await win.screenshot({ path: out + '/tm-result.png' });
  await win.evaluate(() => document.querySelector('.tm-go .btn:not(.tm-big)').click());
  await win.waitForTimeout(400);
  await win.evaluate(() => document.querySelector('.tm-custom').scrollIntoView());
  await win.screenshot({ path: out + '/tm-custom.png' });
  console.log(logs.join('\n'));
  await app.close();
})();
